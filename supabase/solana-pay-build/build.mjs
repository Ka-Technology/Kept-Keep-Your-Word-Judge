// Bundles supabase/functions/solana-pay/index.ts and everything it imports from npm: into one file,
// ../functions/solana-pay/bundle.js, which config.toml's [functions.solana-pay] entrypoint deploys.
// Supabase's own bundler timed out on the Solana packages (2026-10-26), so they're built in here, on
// this machine, from the versions pinned in package.json (the same exact versions index.ts names).
// Only npm:@supabase/* stays an import: Supabase resolves it, as for the other functions.
import { build } from 'esbuild';

/** `npm:@solana/rpc@8.5.0/x` becomes `@solana/rpc/x`, resolved from this folder's node_modules. */
const fromNpm = {
  name: 'npm-specifiers',
  setup(b) {
    // The Node builds import Node's built-ins bare; Deno wants them as node:events and so on, and has them.
    b.onResolve({ filter: /^(events|fs\/promises|path)$/ }, (args) => ({ path: `node:${args.path}`, external: true }));
    b.onResolve({ filter: /^npm:/ }, async (args) => {
      const spec = args.path.slice('npm:'.length);
      if (spec.startsWith('@supabase/')) return { path: args.path, external: true };
      const [, name, subpath = ''] = spec.match(/^(@[^/]+\/[^@/]+|[^@/]+)(?:@[^/]*)?(\/.*)?$/);
      const resolved = await b.resolve(name + subpath, { resolveDir: import.meta.dirname, kind: args.kind });
      if (resolved.errors.length) return { errors: resolved.errors };
      return { path: resolved.path };
    });
  },
};

await build({
  entryPoints: [new URL('../functions/solana-pay/index.ts', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')],
  outfile: new URL('../functions/solana-pay/bundle.js', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  // The packages' Node builds, which Deno runs as it would after `npm:` resolution. Their browser builds refuse
  // to sign unless the runtime says it's a secure browser context, which Deno doesn't (found by running the bundle).
  conditions: ['node', 'import', 'module'],
  mainFields: ['module', 'main'],
  target: 'es2022',
  legalComments: 'none',
  // The Solana packages use Node's Buffer; Deno only provides it to code loaded as an npm: package, not to a bundle
  // (found on Supabase's runtime: "Buffer is not defined").
  banner: {
    js: [
      '// Generated by supabase/solana-pay-build (npm run build) from ../index.ts. Do not edit.',
      'import { Buffer as NodeBuffer } from "node:buffer";',
      'globalThis.Buffer ??= NodeBuffer;',
    ].join('\n'),
  },
  plugins: [fromNpm],
  logLevel: 'info',
});
